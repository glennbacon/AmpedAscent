// End-to-end smoke: boot → Endless → drive with the keyboard → pause/resume → game over → garage → adventure → editor.
import { createRequire } from 'node:module';
// Playwright is not a project dependency: use a local install if present, else the machine-wide one.
let require = createRequire(import.meta.url);
try { require.resolve('playwright'); } catch { require = createRequire(process.env.PLAYWRIGHT_DIR ?? '/opt/node-tools/node_modules/'); }
const { chromium } = require('playwright');
const S = process.argv[2];
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 620 }, deviceScaleFactor: 1 });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
page.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message + '\n' + (e.stack ?? '')));
const st = () => page.evaluate(() => { const g = window.__game, s = g.sim; return { phase: g.phase, screen: g.menus.current, x: +s.vehicle.x.toFixed(1), live: s.live, status: s.status, bat: Math.round(s.battery), coins: g.save.data.coins, frames: window.__frames }; });
const log = async (label) => console.log(label, JSON.stringify(await st()));
await page.goto('http://localhost:5173/?reset&q=low&mute&seed=11', { waitUntil: 'load' });
await page.waitForTimeout(1500); await log('boot');
await page.click('text=Endless Drive'); await page.waitForTimeout(600); await log('after click endless');
await page.keyboard.down('ArrowRight'); await page.waitForTimeout(6000); await log('after 6s gas');
await page.screenshot({ path: `${S}/e1.png` });
await page.keyboard.press('Escape'); await page.waitForTimeout(400); await log('paused');
await page.screenshot({ path: `${S}/e2.png` });
await page.click('text=Resume'); await page.waitForTimeout(300); await log('resumed');
// drain the battery quickly to reach game over
await page.keyboard.up('ArrowRight');
await page.evaluate(() => { window.__drain = setInterval(() => { window.__game.sim.battery = 0; }, 50); });
await page.waitForFunction(() => window.__game.menus.current === 'gameover', null, { timeout: 60000 });
await page.evaluate(() => clearInterval(window.__drain)); await log('after drain');
await page.screenshot({ path: `${S}/e3.png` });
await page.click('text=Garage'); await page.waitForTimeout(800); await log('garage');
await page.evaluate(() => { window.__game.save.data.coins = 5000; window.__game.save.commit(); window.__game.menus.showGarage('upgrades'); });
await page.click('.up .btn.gold'); await page.waitForTimeout(400); await log('bought');
await page.click('text=Tuning'); await page.waitForTimeout(300);
await page.click('text=Climber'); await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/e4.png` });
await page.click('.gtop .btn'); await page.waitForTimeout(600); await log('title');
await page.click('text=Adventure'); await page.waitForTimeout(400);
await page.click('.lvl.next'); await page.waitForTimeout(800); await log('campaign w1-l1');
await page.keyboard.down('ArrowRight'); await page.waitForTimeout(3000); await page.keyboard.up('ArrowRight');
await page.screenshot({ path: `${S}/e5.png` });
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await page.click('text=Quit to menu'); await page.waitForTimeout(600); await log('title2');
await page.click('text=My Levels'); await page.waitForTimeout(300);
await page.click('text=New level'); await page.waitForTimeout(1200); await log('editor');
// sculpt: drag the ground up
await page.mouse.move(600, 330); await page.mouse.down(); await page.mouse.move(600, 230, { steps: 6 }); await page.mouse.up();
await page.waitForTimeout(500);
await page.click('.ebar.bottom >> text=Coin'); await page.mouse.click(520, 250); await page.mouse.click(560, 240);
await page.click('.ebar.bottom >> text=Ramp'); await page.waitForTimeout(200);
await page.click('.picker >> text=Loop'); await page.waitForTimeout(200);
await page.evaluate(() => { const e = window.__game.editor; e.setLength(300); });
await page.waitForTimeout(400);
await page.screenshot({ path: `${S}/e6.png` });
console.log('level', JSON.stringify(await page.evaluate(() => { const l = window.__game.editor.level; return { len: l.length, maxH: Math.max(...l.heights).toFixed(2), pickups: l.pickups.length, props: l.props.length }; })));
await page.click('text=Save'); await page.waitForTimeout(300);
await page.click('.ebar >> text=Test'); await page.waitForTimeout(700); await log('testing');
await page.keyboard.down('ArrowRight'); await page.waitForTimeout(2500); await page.keyboard.up('ArrowRight');
await page.screenshot({ path: `${S}/e7.png` });
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await page.click('text=Edit level'); await page.waitForTimeout(700); await log('back in editor');
await page.click('.ebar >> text=Exit'); await page.waitForTimeout(700); await log('levels list');
await page.screenshot({ path: `${S}/e8.png` });
console.log('ERRORS', errs.length, errs.slice(0, 6).join('\n---\n'));
await browser.close();
